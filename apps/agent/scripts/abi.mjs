// Writes PayRun's ABI from the Foundry build (contracts/out) into src/abi.ts, so the agent's types follow the
// contract. Run after `forge build`: npm run abi
import { readFileSync, writeFileSync } from 'node:fs';
const out = JSON.parse(readFileSync(new URL('../../../contracts/out/PayRun.sol/PayRun.json', import.meta.url), 'utf8'));
const src = `// Generated by scripts/abi.mjs from contracts/out/PayRun.sol/PayRun.json. Do not edit by hand.\nexport const payRunAbi = ${JSON.stringify(out.abi, null, 2)} as const;\n`;
writeFileSync(new URL('../src/abi.ts', import.meta.url), src);
console.log(`wrote src/abi.ts (${out.abi.length} entries)`);
